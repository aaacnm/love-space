const CITIES = RAW.map(([name, lat, lng, region]) => ({ name, lat, lng, region }))

const normalize = (s = '') => s.replace(/[\s省市区县自治州地区]/g, '')

export function lookupCity(text) {
  if (!text) return null
  const key = normalize(String(text))
  if (!key) return null
  const exact = CITIES.find((c) => c.name === key)
  if (exact) return exact
  // 允许「浙江杭州」「杭州市」这类写法
  return CITIES.find((c) => key.includes(c.name) || c.name.includes(key)) || null
}

// 球面直线距离（km）
export function distanceKm(a, b) {
  const R = 6371
  const toRad = (d) => (d * Math.PI) / 180
  const dLat = toRad(b.lat - a.lat)
  const dLng = toRad(b.lng - a.lng)
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2
  return Math.round(2 * R * Math.asin(Math.sqrt(h)))
}
